"""The simulated attractions behind `sim_tickets` (ticketed sights, bought by the agent on our
demo ticket shop) and `sim_sights` (free sights, ideas only).

Real places with approximate coordinates, typical opening hours and plausible prices in PLN
per person (grosze). Nothing here is bought anywhere: the ticket shop is
`/api/demo-supplier/tickets` (dev/test only).
"""

from dataclasses import dataclass

from app.core.domain.attractions import AttractionKind as K


@dataclass(frozen=True, slots=True)
class CatalogueAttraction:
    code: str  # stable, URL-safe: "prg-national-museum"
    title: str
    kind: K
    lat: float
    lon: float
    opens: str  # "10:00"
    closes: str  # "18:00"
    minutes: int
    price_pp_minor: int  # 0 = free entry
    website: str = ""

    @property
    def ticketed(self) -> bool:
        return self.price_pp_minor > 0


@dataclass(frozen=True, slots=True)
class City:
    name: str
    aliases: tuple[str, ...]
    centre: tuple[float, float]
    attractions: tuple[CatalogueAttraction, ...]


