def find_city(name: str) -> City | None:
    folded = name.casefold().strip()
    if not folded:
        return None
    return next((city for city in CITIES if any(alias in folded for alias in city.aliases)), None)


def find_attraction(code: str) -> CatalogueAttraction | None:
    return next(
        (
            attraction
            for city in CITIES
            for attraction in city.attractions
            if attraction.code == code
        ),
        None,
    )
